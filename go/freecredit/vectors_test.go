func b64(b []byte) string { return base64.StdEncoding.EncodeToString(b) }

// randomBlock is every random input: the day key, the keys at and beyond the
// policy's bounds, and two credits under the day key for vecNode on vecEpoch,
// the second chosen so its signature plus the modulus still fits the modulus
// size.
type randomBlock struct {
	DayKeyPKCS8    string `json:"day_key_pkcs8"`
	SmallKeySPKI   string `json:"small_key_spki"`
	MaxKeySPKI     string `json:"max_key_spki"`
	LargeKeySPKI   string `json:"large_key_spki"`
	Nonce          string `json:"nonce"`
	Signature      string `json:"signature"`
	PlusModNonce   string `json:"plus_modulus_nonce"`
	PlusModSigBase string `json:"plus_modulus_signature"`
}

