// vectorIssuers are the localnet issuer and a second fixed key, which no case
// trusts unless it says so.
func vectorIssuers(t *testing.T) (issuer, other ed25519.PrivateKey) {
	t.Helper()
	raw, err := os.ReadFile(localnetPEM)
	if err != nil {
		t.Fatal(err)
	}
	if issuer, err = freecredit.ParseIssuerPEM(raw); err != nil {
		t.Fatal(err)
	}
	seed := sha256.Sum256([]byte("zs free credit vectors: the other issuer"))
	return issuer, ed25519.NewKeyFromSeed(seed[:])
}

func pkcs8(t *testing.T, k any) string {
	t.Helper()
	der, err := x509.MarshalPKCS8PrivateKey(k)
	if err != nil {
		t.Fatal(err)
	}
	return b64(der)
}

func spkiOf(t *testing.T, k *rsa.PublicKey) string {
	t.Helper()
	der, err := x509.MarshalPKIXPublicKey(k)
	if err != nil {
		t.Fatal(err)
	}
	return b64(der)
}

func mustDecode(t *testing.T, s string) []byte {
	t.Helper()
	b, err := base64.StdEncoding.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// daySigner is the random block's day key, certified by issuer for vecDep and
// vecEpoch. The certificate is Ed25519, so deterministic.
func daySigner(t *testing.T, r randomBlock, issuer ed25519.PrivateKey) *freecredit.DaySigner {
	t.Helper()
	k, err := x509.ParsePKCS8PrivateKey(mustDecode(t, r.DayKeyPKCS8))
	if err != nil {
		t.Fatal(err)
	}
	sk := k.(*rsa.PrivateKey)
	spki := mustDecode(t, spkiOf(t, &sk.PublicKey))
	cert := freecredit.DayKeyCert{
		Issuer: freecredit.Bytes(issuer.Public().(ed25519.PublicKey)), Epoch: vecEpoch, DayKey: spki,
		CertSig: ed25519.Sign(issuer, freecredit.DayKeyCertMessage(vecDep, vecEpoch, spki)),
	}
	s, err := freecredit.RestoreDaySigner(sk, issuer.Public().(ed25519.PublicKey), vecDep, cert)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func issueOne(t *testing.T, s *freecredit.DaySigner) freecredit.Credit {
	t.Helper()
	blinded, p, err := freecredit.Blind(nil, s.Key(), vecDep, vecNode)
	if err != nil {
		t.Fatal(err)
	}
	sig, err := s.Sign(blinded)
	if err != nil {
		t.Fatal(err)
	}
	c, err := p.Finalize(sig)
	if err != nil {
		t.Fatal(err)
	}
	return c
}

func modulusOf(t *testing.T, s *freecredit.DaySigner) *big.Int {
	t.Helper()
	pk, err := freecredit.ParseDayKeySPKI(s.Key().Cert().DayKey)
	if err != nil {
		t.Fatal(err)
	}
	return pk.N
}

// plusModulus is sig + N when that still fits the modulus size, and nil
// otherwise.
func plusModulus(sig []byte, n *big.Int) []byte {
	s := new(big.Int).Add(new(big.Int).SetBytes(sig), n)
	if s.BitLen() > len(sig)*8 {
		return nil
	}
	return s.FillBytes(make([]byte, len(sig)))
}

func maxKeySPKI(t *testing.T) string {
	t.Helper()
	k, err := rsa.GenerateKey(rand.Reader, 4096)
	if err != nil {
		t.Fatal(err)
	}
	return spkiOf(t, &k.PublicKey)
}

func generateRandom(t *testing.T, issuer ed25519.PrivateKey) randomBlock {
	t.Helper()
	day, err := rsa.GenerateKey(rand.Reader, freecredit.DayKeyBits)
	if err != nil {
		t.Fatal(err)
	}
	small, err := rsa.GenerateKey(rand.Reader, 1024)
	if err != nil {
		t.Fatal(err)
	}
	large, err := rsa.GenerateKey(rand.Reader, 4104)
	if err != nil {
		t.Fatal(err)
	}
	r := randomBlock{DayKeyPKCS8: pkcs8(t, day), SmallKeySPKI: spkiOf(t, &small.PublicKey), LargeKeySPKI: spkiOf(t, &large.PublicKey)}
	r.MaxKeySPKI = maxKeySPKI(t)
	s := daySigner(t, r, issuer)
	c := issueOne(t, s)
	r.Nonce, r.Signature = b64(c.Nonce), b64(c.Signature)
	n := modulusOf(t, s)
	for {
		c := issueOne(t, s)
		if plusModulus(c.Signature, n) != nil {
			r.PlusModNonce, r.PlusModSigBase = b64(c.Nonce), b64(c.Signature)
			return r
		}
	}
}

func messageCases(t *testing.T) []messageCase {
	t.Helper()
	inputs := []struct {
		dep   ticket.DeploymentID
		node  freecredit.Node
		epoch freecredit.Epoch
		nonce byte
	}{
		{vecDep, vecNode, vecEpoch, 0xa5},
		{ticket.DeploymentID{}, freecredit.Node{}, 0, 0x00},
		// The widest values: a twin that wrote the ids as 53-bit numbers or the
		// epoch as signed would differ here.
		{vecDep, freecredit.Node{Operator: 1<<64 - 1, Node: 1 << 63}, 1<<32 - 1, 0xff},
	}
	var out []messageCase
	for _, in := range inputs {
		nonce := make([]byte, freecredit.NonceSize)
		for i := range nonce {
			nonce[i] = in.nonce ^ byte(i)
		}
		m, err := freecredit.Message(in.dep, in.node, in.epoch, nonce)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, messageCase{
			Deployment: hex.EncodeToString(in.dep[:]), Operator: u64(in.node.Operator), Node: u64(in.node.Node),
			Epoch: uint32(in.epoch), Nonce: hex.EncodeToString(nonce), Message: hex.EncodeToString(m),
		})
	}
	return out
}

func epochCases() []epochCase {
	midnight := int64(20_753) * freecredit.EpochSeconds
	grace := int64(freecredit.Grace / time.Second)
	var out []epochCase
	for _, s := range []int64{0, 1, 86399, 86400, midnight - grace - 1, midnight - grace, midnight - 1, midnight, midnight + grace - 1, midnight + grace} {
		at := time.Unix(s, 0)
		var acc []uint32
		for _, e := range freecredit.AcceptedEpochs(at) {
			acc = append(acc, uint32(e))
		}
		out = append(out, epochCase{Unix: strconv.FormatInt(s, 10), Epoch: uint32(freecredit.EpochAt(at)), Accepted: acc})
	}
	return out
}

func policyCases(t *testing.T, r randomBlock, s *freecredit.DaySigner) []policyCase {
	t.Helper()
	good := s.Key().Cert().DayKey
	pk, _ := freecredit.ParseDayKeySPKI(good)
	out := []policyCase{
		{"day_key", b64(good), true},
		{"1024_bits", r.SmallKeySPKI, false},
		{"4096_bits", r.MaxKeySPKI, true},
		{"4104_bits", r.LargeKeySPKI, false},
		{"exponent_3", spkiOf(t, &rsa.PublicKey{N: pk.N, E: 3}), false},
		{"trailing_byte", b64(append(slices.Clone(good), 0)), false},
	}
	for i := range out {
		_, err := freecredit.ParseDayKeySPKI(mustDecode(t, out[i].SPKI))
		if (err == nil) != out[i].OK {
			t.Fatalf("policy %s: ParseDayKeySPKI = %v, the case says ok=%v", out[i].Name, err, out[i].OK)
		}
	}
	return out
}

