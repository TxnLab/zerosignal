func verifyCases(t *testing.T, r randomBlock, s *freecredit.DaySigner, issuer, other ed25519.PrivateKey) []verifyCase {
	t.Helper()
	base := freecredit.Credit{DayKeyCert: s.Key().Cert(), Nonce: mustDecode(t, r.Nonce), Signature: mustDecode(t, r.Signature)}
	mod := func(f func(c *freecredit.Credit)) freecredit.Credit {
		c := base
		c.Issuer, c.DayKey, c.CertSig = slices.Clone(base.Issuer), slices.Clone(base.DayKey), slices.Clone(base.CertSig)
		c.Nonce, c.Signature = slices.Clone(base.Nonce), slices.Clone(base.Signature)
		f(&c)
		return c
	}
	marshal := func(c freecredit.Credit) json.RawMessage {
		raw, err := json.Marshal(c)
		if err != nil {
			t.Fatal(err)
		}
		return raw
	}
	// respell swaps the base credit's nonce string for another spelling.
	respell := func(spelling string) json.RawMessage {
		raw := marshal(base)
		old, _ := json.Marshal(b64(base.Nonce))
		nu, _ := json.Marshal(spelling)
		out := bytes.Replace(raw, old, nu, 1)
		if bytes.Equal(out, raw) {
			t.Fatal("respell matched nothing")
		}
		return out
	}
	// rewrite edits the base credit's JSON text, for the spellings Marshal
	// never writes.
	rewrite := func(old, nu string) json.RawMessage {
		raw := marshal(base)
		out := bytes.Replace(raw, []byte(old), []byte(nu), 1)
		if bytes.Equal(out, raw) {
			t.Fatalf("rewrite matched no %q", old)
		}
		return out
	}
	// certified is the base credit under spki, which the trusted issuer
	// properly certified, so only the key rules can refuse it.
	certified := func(spki []byte) json.RawMessage {
		return marshal(mod(func(c *freecredit.Credit) {
			c.DayKey = spki
			c.CertSig = ed25519.Sign(issuer, freecredit.DayKeyCertMessage(vecDep, vecEpoch, spki))
		}))
	}
	dayPK, err := freecredit.ParseDayKeySPKI(base.DayKey)
	if err != nil {
		t.Fatal(err)
	}
	epochText := `"epoch":` + strconv.FormatUint(uint64(vecEpoch), 10) + `,`
	nonce := b64(base.Nonce)
	// 32 bytes leave 2 unused bits in the 43rd character, which a canonical
	// encoding leaves clear; setting one is the same bytes to a lax decoder.
	last := strings.IndexByte("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/", nonce[42])
	lax := nonce[:42] + string("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"[last|1]) + nonce[43:]
	plus := freecredit.Credit{DayKeyCert: base.DayKeyCert, Nonce: mustDecode(t, r.PlusModNonce),
		Signature: plusModulus(mustDecode(t, r.PlusModSigBase), modulusOf(t, s))}

	dep := hex.EncodeToString(vecDep[:])
	op, node := u64(vecNode.Operator), u64(vecNode.Node)
	e := uint32(vecEpoch)
	one := []string{"issuer"}
	type spec struct {
		name     string
		issuers  []string
		dep      string
		op, node string
		epochs   []uint32
		credit   json.RawMessage
	}
	specs := []spec{
		{"accept", one, dep, op, node, []uint32{e}, marshal(base)},
		{"accept_neighbouring_epoch", one, dep, op, node, []uint32{e + 1, e}, marshal(base)},
		{"another_node_of_the_operator", one, dep, op, u64(vecNode.Node + 1), []uint32{e}, marshal(base)},
		{"another_operator", one, dep, u64(vecNode.Operator + 1), node, []uint32{e}, marshal(base)},
		{"another_deployment", one, hex.EncodeToString(make([]byte, 32)), op, node, []uint32{e}, marshal(base)},
		{"another_day", one, dep, op, node, []uint32{e + 1}, marshal(base)},
		{"epoch_field_rewritten", one, dep, op, node, []uint32{e + 1}, marshal(mod(func(c *freecredit.Credit) { c.Epoch++ }))},
		{"untrusted_issuer", []string{"other"}, dep, op, node, []uint32{e}, marshal(base)},
		{"names_another_trusted_issuer", []string{"issuer", "other"}, dep, op, node, []uint32{e},
			marshal(mod(func(c *freecredit.Credit) { c.Issuer = freecredit.Bytes(other.Public().(ed25519.PublicKey)) }))},
		{"day_key_swapped", one, dep, op, node, []uint32{e}, marshal(mod(func(c *freecredit.Credit) { c.DayKey = mustDecode(t, r.SmallKeySPKI) }))},
		{"flipped_signature_bit", one, dep, op, node, []uint32{e}, marshal(mod(func(c *freecredit.Credit) { c.Signature[17] ^= 0x01 }))},
		{"signature_plus_modulus", one, dep, op, node, []uint32{e}, marshal(plus)},
		{"short_nonce", one, dep, op, node, []uint32{e}, marshal(mod(func(c *freecredit.Credit) { c.Nonce = c.Nonce[:freecredit.NonceSize-1] }))},
		{"short_issuer", one, dep, op, node, []uint32{e}, marshal(mod(func(c *freecredit.Credit) { c.Issuer = c.Issuer[:31] }))},
		{"no_signature", one, dep, op, node, []uint32{e}, marshal(mod(func(c *freecredit.Credit) { c.Signature = nil }))},
		{"nonce_noncanonical_base64", one, dep, op, node, []uint32{e}, respell(lax)},
		{"nonce_line_break", one, dep, op, node, []uint32{e}, respell(nonce[:20] + "\n" + nonce[20:])},
		{"certified_1024_bit_key", one, dep, op, node, []uint32{e}, certified(mustDecode(t, r.SmallKeySPKI))},
		{"certified_exponent_3_key", one, dep, op, node, []uint32{e}, certified(mustDecode(t, spkiOf(t, &rsa.PublicKey{N: dayPK.N, E: 3})))},
		// Two faults at once pin the order the checks run in.
		{"untrusted_issuer_on_another_day", []string{"other"}, dep, op, node, []uint32{e + 1}, marshal(base)},
		{"short_nonce_from_untrusted_issuer", []string{"other"}, dep, op, node, []uint32{e},
			marshal(mod(func(c *freecredit.Credit) { c.Nonce = c.Nonce[:freecredit.NonceSize-1] }))},
		{"another_day_and_another_deployment", one, hex.EncodeToString(make([]byte, 32)), op, node, []uint32{e + 1}, marshal(base)},
		// The JSON is read as JSON.parse reads it: any integral number is an
		// epoch, names match exactly, and the last of a repeated name wins.
		{"epoch_decimal_point", one, dep, op, node, []uint32{e}, rewrite(epochText, `"epoch":`+u64(uint64(e))+`.0,`)},
		{"epoch_exponent", one, dep, op, node, []uint32{e}, rewrite(epochText, `"epoch":2.0752e4,`)},
		{"epoch_fraction", one, dep, op, node, []uint32{e}, rewrite(epochText, `"epoch":`+u64(uint64(e))+`.5,`)},
		{"epoch_quoted", one, dep, op, node, []uint32{e}, rewrite(epochText, `"epoch":"`+u64(uint64(e))+`",`)},
		// The largest u32 parses, and is refused only as a day not accepted;
		// one more is no epoch at all.
		{"epoch_max", one, dep, op, node, []uint32{e}, rewrite(epochText, `"epoch":4294967295,`)},
		{"epoch_past_max", one, dep, op, node, []uint32{e}, rewrite(epochText, `"epoch":4294967296,`)},
		{"nonce_name_in_another_case", one, dep, op, node, []uint32{e}, rewrite(`"nonce":`, `"NONCE":`)},
		{"another_case_name_ignored", one, dep, op, node, []uint32{e}, rewrite(`"signature":`, `"Nonce":"AAAA","signature":`)},
		{"repeated_name_last_wins", one, dep, op, node, []uint32{e}, rewrite(`"signature":`, `"nonce":"AAAA","signature":`)},
		{"repeated_name_earlier_ignored", one, dep, op, node, []uint32{e}, rewrite(`"issuer":`, `"nonce":"AAAA","issuer":`)},
	}
	if vecEpoch != 20_752 {
		t.Fatal("epoch_exponent spells vecEpoch as 2.0752e4")
	}
	var out []verifyCase
	for _, s := range specs {
		out = append(out, verifyCase{Name: s.name, Issuers: s.issuers, Deployment: s.dep, Operator: s.op, Node: s.node, Epochs: s.epochs, Credit: s.credit})
	}
	return out
}

// runVerify is ParseCredit then Verify over one case, as both languages run it.
func runVerify(t *testing.T, vc verifyCase, issuers map[string]ed25519.PublicKey) string {
	t.Helper()
	var trusted []ed25519.PublicKey
	for _, name := range vc.Issuers {
		k, ok := issuers[name]
		if !ok {
			t.Fatalf("%s: no issuer %q", vc.Name, name)
		}
		trusted = append(trusted, k)
	}
	depBytes, err := hex.DecodeString(vc.Deployment)
	if err != nil || len(depBytes) != 32 {
		t.Fatalf("%s: deployment %q", vc.Name, vc.Deployment)
	}
	var dep ticket.DeploymentID
	copy(dep[:], depBytes)
	op, err1 := strconv.ParseUint(vc.Operator, 10, 64)
	node, err2 := strconv.ParseUint(vc.Node, 10, 64)
	if err1 != nil || err2 != nil {
		t.Fatalf("%s: node %s/%s", vc.Name, vc.Operator, vc.Node)
	}
	c, err := freecredit.ParseCredit(vc.Credit)
	if err != nil {
		return freecredit.Reason(err)
	}
	epochs := make([]freecredit.Epoch, len(vc.Epochs))
	for i, e := range vc.Epochs {
		epochs[i] = freecredit.Epoch(e)
	}
	return freecredit.Reason(freecredit.Verify(trusted, dep, freecredit.Node{Operator: op, Node: node}, epochs, c))
}

// derive builds the whole file from its random block.
func derive(t *testing.T, r randomBlock, issuer, other ed25519.PrivateKey) vectorsFile {
	t.Helper()
	s := daySigner(t, r, issuer)
	spki := s.Key().Cert().DayKey
	f := vectorsFile{
		Version:   1,
		Comment:   vectorComment,
		Variant:   "RSABSSA-SHA384-PSS-Deterministic",
		GraceSecs: int(freecredit.Grace / time.Second),
		Random:    r,
		Issuers: map[string]issuerEntry{
			"issuer": {Key: b64(issuer.Public().(ed25519.PublicKey)), PKCS8: pkcs8(t, issuer)},
			"other":  {Key: b64(other.Public().(ed25519.PublicKey)), PKCS8: pkcs8(t, other)},
		},
		Messages: messageCases(t),
		Epochs:   epochCases(),
		CertMessage: certCase{Deployment: hex.EncodeToString(vecDep[:]), Epoch: uint32(vecEpoch), DayKey: b64(spki),
			Message: hex.EncodeToString(freecredit.DayKeyCertMessage(vecDep, vecEpoch, spki))},
		Policy: policyCases(t, r, s),
		Verify: verifyCases(t, r, s, issuer, other),
	}
	keys := map[string]ed25519.PublicKey{"issuer": issuer.Public().(ed25519.PublicKey), "other": other.Public().(ed25519.PublicKey)}
	for i := range f.Verify {
		f.Verify[i].Reason = runVerify(t, f.Verify[i], keys)
	}
	return f
}

// holds is whether a derived file gets every verdict it should.
func holds(f vectorsFile) bool {
	if len(f.Verify) != len(verifyCaseNames) {
		return false
	}
	for i, vc := range f.Verify {
		if vc.Name != verifyCaseNames[i] || vc.Reason != wantReasons[vc.Name] {
			return false
		}
	}
	return true
}

func encodeVectors(t *testing.T, f vectorsFile) []byte {
	t.Helper()
	raw, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(raw, '\n')
}

func readRandom(t *testing.T) (randomBlock, []byte, bool) {
	t.Helper()
	raw, err := os.ReadFile(vectorsPath)
	if err != nil {
		return randomBlock{}, nil, false
	}
	var f vectorsFile
	if json.Unmarshal(raw, &f) != nil || f.Random.DayKeyPKCS8 == "" {
		return randomBlock{}, raw, false
	}
	return f.Random, raw, true
}

func TestFreeCreditVectors(t *testing.T) {
	issuer, other := vectorIssuers(t)
	if *updateVectors {
		var f vectorsFile
		if r, _, ok := readRandom(t); ok {
			// A field added to the block since the file was written is drawn
			// alone, so the rest of the block, and its signatures, stay.
			if r.MaxKeySPKI == "" {
				r.MaxKeySPKI = maxKeySPKI(t)
			}
			f = derive(t, r, issuer, other)
		}
		if !holds(f) {
			f = derive(t, generateRandom(t, issuer), issuer, other)
		}
		if !holds(f) {
			t.Fatal("a fresh random block does not reach every verdict")
		}
		if err := os.WriteFile(vectorsPath, encodeVectors(t, f), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	r, raw, ok := readRandom(t)
	if !ok {
		t.Fatal("free_credit_vectors.json is missing or has no random block; regenerate with -update")
	}
	want := derive(t, r, issuer, other)
	if !holds(want) {
		t.Fatal("the file's random block no longer reaches every verdict; regenerate with -update")
	}
	if !bytes.Equal(raw, encodeVectors(t, want)) {
		t.Fatal("free_credit_vectors.json is stale; regenerate with -update")
	}
}
