const wireVectorsPath = "../../../testdata/solana_wire_vectors.json"

type wireOpenCase struct {
	Name        string `json:"name"`
	Presigned   string `json:"presigned_open_txn"`
	PaymentOpen string `json:"payment_open"`
	PaymentRef  string `json:"payment_ref"`
}

type wireOpenRefusal struct {
	Name        string `json:"name"`
	About       string `json:"about"`
	PaymentOpen string `json:"payment_open"`
	PaymentRef  string `json:"payment_ref"`
}

type wireOfferRefusal struct {
	Name      string `json:"name"`
	About     string `json:"about"`
	Presigned string `json:"presigned_open_txn"`
}

type wireEncodeRefusal struct {
	Name      string `json:"name"`
	About     string `json:"about"`
	Completed string `json:"completed_base64"`
}

type wireOpenSeqCase struct {
	Slot  string `json:"slot"`
	Value string `json:"value,omitempty"`
	OK    bool   `json:"ok"`
}

type wireAckCase struct {
	Name          string          `json:"name"`
	About         string          `json:"about"`
	Signer        string          `json:"signer"`
	OperatorID    string          `json:"operator_id"`
	NodeID        string          `json:"node_id"`
	TicketID      string          `json:"ticket_id"`
	OpenSeq       string          `json:"open_seq"`
	Receipt       json.RawMessage `json:"receipt"`
	PaymentSettle string          `json:"payment_settle,omitempty"`
	Verdict       string          `json:"verdict"`
}

type wireSettleRefusal struct {
	Name          string `json:"name"`
	PaymentSettle string `json:"payment_settle"`
}

type wireVectors struct {
	Version        int                 `json:"version"`
	Comment        string              `json:"comment"`
	ProgramID      string              `json:"program_id"`
	Mint           string              `json:"usdc_mint"`
	GenesisHash    string              `json:"genesis_hash"`
	Opens          []wireOpenCase      `json:"opens"`
	OpenRefusals   []wireOpenRefusal   `json:"open_refusals"`
	OfferRefusals  []wireOfferRefusal  `json:"offer_refusals"`
	EncodeRefusals []wireEncodeRefusal `json:"encode_refusals"`
	OpenSeqs       []wireOpenSeqCase   `json:"open_seqs"`
	Acks           []wireAckCase       `json:"acks"`
	SettleRefusals []wireSettleRefusal `json:"settle_refusals"`
}

// bytesSigner signs digests as the keys it holds, by base58 address.
type bytesSigner map[string]ed25519.PrivateKey

func (s bytesSigner) SignBytes(_ context.Context, address string, msg []byte) ([]byte, error) {
	k, ok := s[address]
	if !ok {
		return nil, errors.New("no key for " + address)
	}
	return ed25519.Sign(k, msg), nil
}

func buildWireVectors(t *testing.T) wireVectors {
	w := loadAckWorld(t)
	v := wireVectors{
		Version: 1,
		Comment: strings.Join([]string{
			"The Solana values of the open and ack wire fields (SPEC.md § 3a, § 4). Generated by go/solana/zsescrow wire_vectors_test.go; do not edit.",
			"opens: solana_sign_vectors.json's open offers as presigned_open_txn, and the payment_open and payment_ref the payer writes once it signs; the node reads them back.",
			"open_refusals: payment_open and payment_ref the node's reading refuses.",
			"offer_refusals: presigned_open_txn values the payer's reading refuses.",
			"encode_refusals: completed opens, in base64, the payer refuses to write as payment_open because a signature does not verify.",
			"open_seqs: settle-group slot values, and the open_seq each reads as, or not.",
			"acks: payment_settle for a receipt, signed by a key of solana_tx_vectors.json's context, or the AckRejectedError slug that refuses the receipt. ticket_id is hex.",
			"settle_refusals: payment_settle values the node's reading refuses.",
		}, " "),
		ProgramID: w.d.Program.String(), Mint: w.d.Mint.String(), GenesisHash: hex.EncodeToString(w.genesis[:]),
	}

	sv := buildSignVectors(t)
	for _, c := range sv.Offers {
		open, ref, err := zsescrow.EncodeOpenPayment(b64(t, c.Wire))
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		v.Opens = append(v.Opens, wireOpenCase{Name: c.Name, Presigned: c.Offer, PaymentOpen: open, PaymentRef: ref})
	}
	if len(v.Opens) == 0 {
		t.Fatal("no offers in the sign vectors")
	}

	first := v.Opens[0]
	completed, err := solana.ParseTransaction(b64(t, first.PaymentOpen))
	if err != nil {
		t.Fatal(err)
	}
	refuse := func(name, about, open, ref string) {
		v.OpenRefusals = append(v.OpenRefusals, wireOpenRefusal{Name: name, About: about, PaymentOpen: open, PaymentRef: ref})
	}
	tampered := *completed
	tampered.Signatures = append([]solana.Signature(nil), completed.Signatures...)
	tampered.Signatures[0][0] ^= 1
	tamperedWire, err := tampered.MarshalBinary()
	if err != nil {
		t.Fatal(err)
	}
	refuse("ref_is_the_payers_signature", "payment_ref names the payer's signature, not the first", first.PaymentOpen, completed.Signatures[1].String())
	refuse("no_ref", "payment_ref is empty", first.PaymentOpen, "")
	refuse("offer_unsigned_by_payer", "the offer as the node sent it, the payer's slot empty", first.Presigned, completed.Signatures[0].String())
	refuse("first_signature_tampered", "payment_ref is the first signature, which does not verify", base64.StdEncoding.EncodeToString(tamperedWire), tampered.Signatures[0].String())
	for _, s := range respellings(t, first.PaymentOpen) {
		refuse("open_"+s.name, "payment_open "+s.about, s.value, first.PaymentRef)
	}
	refuse("open_not_a_transaction", "payment_open is base64 of bytes that are no transaction", base64.StdEncoding.EncodeToString([]byte{1, 2, 3}), first.PaymentRef)

	for _, s := range respellings(t, first.Presigned) {
		v.OfferRefusals = append(v.OfferRefusals, wireOfferRefusal{Name: s.name, About: "presigned_open_txn " + s.about, Presigned: s.value})
	}
	v.EncodeRefusals = []wireEncodeRefusal{
		{"payer_slot_empty", "the offer as the node sent it, which the payer has not signed", first.Presigned},
		{"first_signature_tampered", "the node's signature does not verify", base64.StdEncoding.EncodeToString(tamperedWire)},
	}

	for _, s := range []string{"0", "1", "7", "18446744073709551615", "", "01", "00", "+1", "-1", " 1", "1 ", "1\n", "18446744073709551616", "1e3", "0x1", "1_000", "１"} {
		c := wireOpenSeqCase{Slot: s}
		if n, err := zsescrow.ParseOpenSeq(s); err == nil {
			c.OK, c.Value = true, strconv.FormatUint(n, 10)
		}
		v.OpenSeqs = append(v.OpenSeqs, c)
	}

	keys := fixtureKeys(t)
	signer := bytesSigner{}
	for _, k := range keys {
		signer[solana.PublicKey(k.Public().(ed25519.PublicKey)).String()] = k
	}
	spec := w.specFor(t, w.byName["ack_relayed"])
	ack := func(name, about, key string, operatorID, nodeID uint64, ticketID [16]byte, openSeq uint64, r *ticket.UsageReceipt) {
		rj, err := json.Marshal(r)
		if err != nil {
			t.Fatal(err)
		}
		payer := solana.PublicKey(keys[key].Public().(ed25519.PublicKey))
		c := wireAckCase{Name: name, About: about, Signer: key, OperatorID: strconv.FormatUint(operatorID, 10), NodeID: strconv.FormatUint(nodeID, 10),
			TicketID: hex.EncodeToString(ticketID[:]), OpenSeq: strconv.FormatUint(openSeq, 10), Receipt: rj}
		sig, err := zsescrow.SignReceiptAck(context.Background(), signer, payer, w.d, w.genesis, operatorID, nodeID, ticketID, openSeq, r)
		c.Verdict = ackVerdictOf(err)
		c.PaymentSettle = sig
		v.Acks = append(v.Acks, c)
	}
	other := spec.TicketID
	other[0] ^= 1
	ack("receipt_claim", "the payer's ack of the receipt on the relayed ack's ticket", "payer", spec.OperatorID, spec.NodeID, spec.TicketID, 7, spec.Receipt)
	ack("open_seq_zero", "the same at open_seq 0", "payer", spec.OperatorID, spec.NodeID, spec.TicketID, 0, spec.Receipt)
	ack("open_seq_max", "the same at the largest open_seq", "payer", spec.OperatorID, spec.NodeID, spec.TicketID, math.MaxUint64, spec.Receipt)
	ack("another_payer", "the same claim acked by another key", "attacker", spec.OperatorID, spec.NodeID, spec.TicketID, 7, spec.Receipt)
	ack("receipt_of_another_ticket", "the payer's ticket is not the one the receipt names", "payer", spec.OperatorID, spec.NodeID, other, 7, spec.Receipt)
	ack("no_receipt", "the payer holds no receipt for the ticket", "payer", spec.OperatorID, spec.NodeID, spec.TicketID, 7, nil)

	sig := b64(t, v.Acks[0].PaymentSettle)
	v.SettleRefusals = []wireSettleRefusal{
		{"short", base64.StdEncoding.EncodeToString(sig[:63])},
		{"long", base64.StdEncoding.EncodeToString(append(sig[:64:64], 0))},
	}
	// A signature whose base64 uses + or /, which the URL-safe respelling needs.
	respelled := ""
	for _, c := range v.Acks {
		if c.Verdict == "ok" && strings.ContainsAny(c.PaymentSettle, "+/") {
			respelled = c.PaymentSettle
			break
		}
	}
	for _, s := range respellings(t, respelled) {
		v.SettleRefusals = append(v.SettleRefusals, wireSettleRefusal{s.name, s.value})
	}
	return v
}

type respelling struct{ name, about, value string }

// respellings are other spellings of the base64 value s that some decoder
// reads as s's bytes, and the empty string. s must end in padding and use +
// or /, or a respelling would be s itself.
func respellings(t *testing.T, s string) []respelling {
	if !strings.HasSuffix(s, "=") || !strings.ContainsAny(s, "+/") {
		t.Fatalf("%q needs padding and a + or / to be respelled", s)
	}
	const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	// The character before the padding carries 2 or 4 unused low bits, zero
	// in s; setting the lowest leaves the bytes Go decodes unchanged.
	last := len(strings.TrimRight(s, "=")) - 1
	dirty := s[:last] + string(alphabet[strings.IndexByte(alphabet, s[last])|1]) + s[last+1:]
	return []respelling{
		{"with_newline", "with a trailing newline, which Go's decoder skips", s + "\n"},
		{"wrapped", "with a newline inside, which Go's decoder skips", s[:4] + "\r\n" + s[4:]},
		{"unpadded", "without its padding", strings.TrimRight(s, "=")},
		{"url_alphabet", "in the URL-safe alphabet", strings.NewReplacer("+", "-", "/", "_").Replace(s)},
		{"padding_bits", "with unused bits set before the padding, which Go's decoder ignores", dirty},
		{"empty", "empty", ""},
	}
}

func TestWireVectors(t *testing.T) {
	got, err := json.MarshalIndent(buildWireVectors(t), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if *updateVectors {
		if err := os.WriteFile(wireVectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(wireVectorsPath)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("solana_wire_vectors.json is stale: go test ./solana/zsescrow -run TestWireVectors -update")
	}
}

// The readers take back what the writers wrote, refuse every refusal, and an
// ack verifies under its signer over the receipt's ack digest.
func TestWireVectorsMeanWhatTheySay(t *testing.T) {
	v := buildWireVectors(t)
	w := loadAckWorld(t)
	for _, c := range v.Opens {
		offer, err := zsescrow.DecodeOpenOffer(c.Presigned)
		if err != nil || base64.StdEncoding.EncodeToString(offer) != c.Presigned {
			t.Errorf("%s: presigned_open_txn reads back as %x, %v", c.Name, offer, err)
		}
		tx, err := zsescrow.DecodeOpenPayment(c.PaymentOpen, c.PaymentRef)
		if err != nil {
			t.Errorf("%s: %v", c.Name, err)
			continue
		}
		if tx.Signatures[0].String() != c.PaymentRef {
			t.Errorf("%s: payment_ref is not the first signature", c.Name)
		}
	}
	for _, c := range v.OpenRefusals {
		if _, err := zsescrow.DecodeOpenPayment(c.PaymentOpen, c.PaymentRef); err == nil {
			t.Errorf("%s: read", c.Name)
		}
	}
	for _, c := range v.OfferRefusals {
		if _, err := zsescrow.DecodeOpenOffer(c.Presigned); err == nil {
			t.Errorf("%s: read", c.Name)
		}
	}
	for _, c := range v.EncodeRefusals {
		if _, _, err := zsescrow.EncodeOpenPayment(b64(t, c.Completed)); err == nil {
			t.Errorf("%s: written", c.Name)
		}
	}
	// The respellings Go's lenient decoder reads as the value itself are the
	// ones only the canonical rule refuses.
	for _, s := range respellings(t, v.Opens[0].PaymentOpen) {
		if s.name != "with_newline" && s.name != "wrapped" && s.name != "padding_bits" {
			continue
		}
		if got, err := base64.StdEncoding.DecodeString(s.value); err != nil || !bytes.Equal(got, b64(t, v.Opens[0].PaymentOpen)) {
			t.Errorf("%s: Go's decoder reads %x, %v, not the value's bytes", s.name, got, err)
		}
	}
	for _, c := range v.OpenSeqs {
		if !c.OK {
			continue
		}
		n, _ := strconv.ParseUint(c.Value, 10, 64)
		if zsescrow.FormatOpenSeq(n) != c.Slot {
			t.Errorf("open_seq %s writes as %q, read from %q", c.Value, zsescrow.FormatOpenSeq(n), c.Slot)
		}
	}
	keys := fixtureKeys(t)
	for _, c := range v.Acks {
		if c.Verdict != "ok" {
			if c.PaymentSettle != "" {
				t.Errorf("%s: refused with a payment_settle", c.Name)
			}
			continue
		}
		sig, err := zsescrow.DecodeAckSignature(c.PaymentSettle)
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		var r ticket.UsageReceipt
		if err := json.Unmarshal(c.Receipt, &r); err != nil {
			t.Fatal(err)
		}
		op, _ := strconv.ParseUint(c.OperatorID, 10, 64)
		node, _ := strconv.ParseUint(c.NodeID, 10, 64)
		seq, _ := strconv.ParseUint(c.OpenSeq, 10, 64)
		digest, err := zsescrow.ReceiptAckDigest(w.d, w.genesis, op, node, [16]byte(mustHex(t, c.TicketID)), seq, &r)
		if err != nil {
			t.Fatal(err)
		}
		if !solana.VerifyStrict(solana.PublicKey(keys[c.Signer].Public().(ed25519.PublicKey)), digest[:], sig) {
			t.Errorf("%s: payment_settle does not verify under %s", c.Name, c.Signer)
		}
	}
	for _, c := range v.SettleRefusals {
		if _, err := zsescrow.DecodeAckSignature(c.PaymentSettle); err == nil {
			t.Errorf("%s: read", c.Name)
		}
	}
}

// A signer that answers with another key's signature, or a short one, is
// refused before anything reaches the node.
func TestSignReceiptAckRefusesASignatureThatDoesNotVerify(t *testing.T) {
	w := loadAckWorld(t)
	keys := fixtureKeys(t)
	spec := w.specFor(t, w.byName["ack_relayed"])
	payer := solana.PublicKey(keys["payer"].Public().(ed25519.PublicKey))
	for name, s := range map[string]ticket.BytesSigner{
		"another key": signFunc(func(msg []byte) []byte { return ed25519.Sign(keys["attacker"], msg) }),
		"short":       signFunc(func(msg []byte) []byte { return ed25519.Sign(keys["payer"], msg)[:63] }),
		"other bytes": signFunc(func(msg []byte) []byte { return ed25519.Sign(keys["payer"], append([]byte{0}, msg...)) }),
	} {
		if sig, err := zsescrow.SignReceiptAck(context.Background(), s, payer, w.d, w.genesis, spec.OperatorID, spec.NodeID, spec.TicketID, 7, spec.Receipt); err == nil {
			t.Errorf("%s: signed %s", name, sig)
		}
	}
	asked := ""
	s := signFunc(func(msg []byte) []byte { return ed25519.Sign(keys["payer"], msg) })
	if _, err := zsescrow.SignReceiptAck(context.Background(), recordAddress(s, &asked), payer, w.d, w.genesis, spec.OperatorID, spec.NodeID, spec.TicketID, 7, spec.Receipt); err != nil {
		t.Fatal(err)
	}
	if asked != payer.String() {
		t.Errorf("asked to sign as %q, want the payer %s", asked, payer)
	}
}

type signFunc func([]byte) []byte

func (f signFunc) SignBytes(_ context.Context, _ string, msg []byte) ([]byte, error) {
	return f(msg), nil
}

type addressRecorder struct {
	s     ticket.BytesSigner
	asked *string
}

func recordAddress(s ticket.BytesSigner, asked *string) addressRecorder {
	return addressRecorder{s, asked}
}

func (r addressRecorder) SignBytes(ctx context.Context, address string, msg []byte) ([]byte, error) {
	*r.asked = address
	return r.s.SignBytes(ctx, address, msg)
}
