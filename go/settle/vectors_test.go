package settle_test

// Cross-impl parity for the rail-neutral settlement rules: Classify over every
// status at the deadline boundaries, and the fee math. Generates / verifies
// proto/testdata/settle_vectors.json, which proto/ts replays, so a payer's
// watchdog and a node's sweep on either language and either rail reach the
// same verdict and the same fee for the same ticket.
//
// To regenerate after an intentional change:
//
//	cd proto/go && go test ./settle -run TestSettleVectors -update
//
// Without -update, this asserts the on-disk file matches current Go output.

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"strconv"
	"testing"
	"time"

	"github.com/TxnLab/zerosignal/go/settle"
)

var updateVectors = flag.Bool("update", false, "regenerate proto/testdata/settle_vectors.json")

const vectorsPath = "../../testdata/settle_vectors.json"

type classifyCase struct {
	Name      string `json:"name"`
	Status    string `json:"status"`
	Deadline  string `json:"deadline"`
	NowUnixMs string `json:"now_unix_ms"`
	Verdict   string `json:"verdict"`
}

type netFeeCase struct {
	AmountCharged string `json:"amount_charged"`
	FeeBps        string `json:"fee_bps"`
	DiscountBps   string `json:"discount_bps"`
	Want          string `json:"want"`
}

type breakdownCase struct {
	AmountCharged string `json:"amount_charged"`
	MaxPrice      string `json:"max_price"`
	FeeBps        string `json:"fee_bps"`
	DiscountBps   string `json:"discount_bps"`
	NetFee        string `json:"net_fee"`
	Refund        string `json:"refund"`
	TotalDebit    string `json:"total_debit"`
}

type vectorsFile struct {
	Version  int             `json:"version"`
	Comment  string          `json:"comment"`
	Statuses map[string]int  `json:"statuses"`
	Classify []classifyCase  `json:"classify"`
	NetFee   []netFeeCase    `json:"net_fee"`
	Fees     []breakdownCase `json:"fee_breakdown"`
}

func u64(v uint64) string { return strconv.FormatUint(v, 10) }

// statusNames keys the fixture by name, so the TS port is checked against the
// numbering too: a twin that swapped two values would otherwise agree on every
// verdict it was fed by name.
var statusNames = []struct {
	name   string
	status settle.Status
}{
	{"unrecognized", settle.StatusUnrecognized},
	{"open", settle.StatusOpen},
	{"pending_payer", settle.StatusPendingPayer},
	{"pending_operator", settle.StatusPendingOperator},
	{"frozen", settle.StatusFrozen},
}

func buildClassify() []classifyCase {
	const deadline = 1_800_000_600
	deadlineMs := int64(deadline) * 1000
	clocks := []struct {
		name string
		ms   int64
	}{
		{"before_deadline", deadlineMs - 60_000},
		{"one_ms_before_deadline", deadlineMs - 1},
		{"at_deadline", deadlineMs},
		{"one_ms_after_deadline", deadlineMs + 1},
		{"long_after_deadline", deadlineMs + 86_400_000},
	}
	var out []classifyCase
	for _, s := range statusNames {
		for _, c := range clocks {
			out = append(out, classifyCase{
				Name: s.name + "/" + c.name, Status: s.name, Deadline: u64(deadline),
				NowUnixMs: strconv.FormatInt(c.ms, 10),
				Verdict:   settle.Classify(settle.Ticket{Status: s.status, Deadline: deadline}, time.UnixMilli(c.ms)).String(),
			})
		}
	}
	// A status beyond the named ones is what a newer decoder could hand an
	// older port; it must stay Unknown, never Wait.
	out = append(out, classifyCase{
		Name: "future_status/long_after_deadline", Status: "9", Deadline: u64(deadline),
		NowUnixMs: strconv.FormatInt(deadlineMs+86_400_000, 10),
		Verdict:   settle.Classify(settle.Ticket{Status: 9, Deadline: deadline}, time.UnixMilli(deadlineMs+86_400_000)).String(),
	})
	return out
}

func buildVectors() vectorsFile {
	v := vectorsFile{
		Version: 1,
		Comment: "Cross-impl golden vectors for proto/go/settle: Classify over the rail-neutral ticket view, and the " +
			"protocol fee math. uint64 values are decimal strings. Generated by proto/go/settle/vectors_test.go; " +
			"regenerate with `cd proto/go && go test ./settle -run TestSettleVectors -update`.",
		Statuses: map[string]int{},
		Classify: buildClassify(),
	}
	for _, s := range statusNames {
		v.Statuses[s.name] = int(s.status)
	}
	for _, c := range [][3]uint64{
		{0, 500, 0}, {1, 500, 0}, {19, 500, 0}, {20, 500, 0}, {1_234_567, 500, 0},
		{1_234_567, 2000, 0}, {1_234_567, 500, 2500}, {1_234_567, 500, 8000},
		{1_234_567, 500, 10_000}, {1_234_567, 500, 12_000}, {999_999_999_999, 2000, 0},
	} {
		v.NetFee = append(v.NetFee, netFeeCase{u64(c[0]), u64(c[1]), u64(c[2]), u64(settle.NetFee(c[0], c[1], c[2]))})
	}
	for _, c := range [][4]uint64{
		{0, 0, 500, 0}, {0, 2_000_000, 500, 0}, {1_000_000, 2_000_000, 500, 0},
		{1_000_000, 1_050_000, 500, 0}, {1_000_000, 1_000_000, 500, 0}, {1_000_000, 1_020_000, 2000, 0},
	} {
		b := settle.ComputeFeeBreakdown(c[0], c[1], c[2], c[3])
		v.Fees = append(v.Fees, breakdownCase{
			u64(c[0]), u64(c[1]), u64(c[2]), u64(c[3]), u64(b.NetFee), u64(b.Refund), u64(b.TotalDebit),
		})
	}
	return v
}

func TestSettleVectors(t *testing.T) {
	got, err := json.MarshalIndent(buildVectors(), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if *updateVectors {
		if err := os.WriteFile(vectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("read %s (run with -update to create it): %v", vectorsPath, err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; regenerate with `go test ./settle -run TestSettleVectors -update`", vectorsPath)
	}
}
