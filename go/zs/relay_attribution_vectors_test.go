package zs

// Generates / verifies proto/testdata/relay_attribution_vectors.json: what one
// relayed forward's outcome records against the relay (relayHopAction), which
// the TS SDK mirrors in sdk/src/routing/attribution.ts. The cases are the full
// cross product of the statuses, codes and route evidence below, one per line.
//
//	cd proto/go && go test ./zs -run TestRelayAttributionVectors -update

import (
	"bytes"
	"encoding/json"
	"os"
	"testing"

	"github.com/TxnLab/zerosignal/go/transient"
)

const relayAttributionVectorsPath = "../../testdata/relay_attribution_vectors.json"

type relayAttributionCase struct {
	Status   int                     `json:"status"`
	Code     string                  `json:"code"`
	Evidence transient.RelayEvidence `json:"evidence"`
	Want     relayAction             `json:"want"`
}

// Every status the verdict treats differently: a transport failure, a success,
// a 3xx (below the error threshold, so even a relay code credits), a plain
// refusal, each retryable and forward-timeout status, and a 429.
var relayAttributionStatuses = []int{transient.TransportFailureStatus, 200, 302, 400, 408, 429, 500, 502, 503, 504, 524}

// No code, a relay hop error, the relay's claim about its target, and a node's.
var relayAttributionCodes = []string{"", "relay_busy", "relay_upstream_unreachable", "provider_unavailable"}

func relayAttributionCases() []relayAttributionCase {
	var out []relayAttributionCase
	for _, status := range relayAttributionStatuses {
		for _, code := range relayAttributionCodes {
			for _, marker := range []bool{false, true} {
				for _, marks := range []bool{false, true} {
					for _, aborted := range []bool{false, true} {
						ev := transient.RelayEvidence{
							Relayed: true, HopMarker: marker, RelayMarksHops: marks, CallerAborted: aborted,
						}
						out = append(out, relayAttributionCase{
							Status: status, Code: code, Evidence: ev, Want: relayHopAction(status, code, ev),
						})
					}
				}
			}
		}
	}
	return out
}

// Each action is reachable from the cross product, so the vectors exercise
// every arm of the TS mirror.
func TestRelayAttributionCoversEveryAction(t *testing.T) {
	seen := map[relayAction]bool{}
	for _, c := range relayAttributionCases() {
		seen[c.Want] = true
	}
	for _, a := range []relayAction{
		relayActionNone, relayActionCredit, relayActionStrike,
		relayActionUpstreamUnreachable, relayActionForwardedTargetFault, relayActionForwardTimeout,
	} {
		if !seen[a] {
			t.Errorf("no case yields %q", a)
		}
	}
}

func TestRelayAttributionVectors(t *testing.T) {
	var buf bytes.Buffer
	buf.WriteString("{\n  \"comment\": \"Generated by proto/go/zs TestRelayAttributionVectors. One case per line; compare want exactly.\",\n  \"cases\": [\n")
	cases := relayAttributionCases()
	for i, c := range cases {
		line, err := json.Marshal(c)
		if err != nil {
			t.Fatal(err)
		}
		buf.WriteString("    ")
		buf.Write(line)
		if i < len(cases)-1 {
			buf.WriteByte(',')
		}
		buf.WriteByte('\n')
	}
	buf.WriteString("  ]\n}\n")
	out := buf.Bytes()

	if *updateVectors {
		if err := os.WriteFile(relayAttributionVectorsPath, out, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(relayAttributionVectorsPath)
	if err != nil {
		t.Fatalf("read vectors (regenerate with -update): %v", err)
	}
	if !bytes.Equal(want, out) {
		t.Fatalf("relay attribution differs from %s; if the change is intended, regenerate with -update and review the diff", relayAttributionVectorsPath)
	}
}
