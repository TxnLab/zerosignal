package zs

// Generates / verifies proto/testdata/deposit_plan_vectors.json: how one
// prepaid-MBR-pool funding pass is sized (planDeposit). The TS SDK mirrors it
// as planMbrDeposit in sdk/src/mbr.ts.
//
//	cd proto/go && go test ./zs -run TestDepositPlanVectors -update

import (
	"bytes"
	"encoding/json"
	"math"
	"os"
	"strconv"
	"testing"

	"github.com/TxnLab/zerosignal/go/escrow"
)

const depositPlanVectorsPath = "../../testdata/deposit_plan_vectors.json"

// Every quantity is a decimal string: µALGO and slot counts are uint64, past
// what a JSON number carries exactly into TypeScript.
type depositPlanCase struct {
	Slots       string `json:"slots"`
	TicketMbr   string `json:"ticketMbr"`
	QuotaDue    string `json:"quotaDue"`
	AlgoBalance string `json:"algoBalance"`
	OpenTickets string `json:"openTickets"`
	OptedIn     bool   `json:"optedIn"`
	Spendable   string `json:"spendable"`
	MinFee      string `json:"minFee"`

	Amount       string `json:"amount"`
	BelowTarget  bool   `json:"belowTarget"`
	Unaffordable bool   `json:"unaffordable"`
	Need         string `json:"need"`
}

func u(v uint64) string { return strconv.FormatUint(v, 10) }

func TestDepositPlanVectors(t *testing.T) {
	const mbr, quota, fee = 115_000, 22_500, 1_000
	type in struct {
		slots, ticketMbr, quotaDue, balance, open uint64
		optedIn                                   bool
		spendable, minFee                         uint64
	}
	var ins []in

	// The grid: pool sizes around whole slots and the quota remainder, wallets
	// from empty to rich and at each affordability edge, three working sets.
	overhead := func(optedIn bool) uint64 {
		if optedIn {
			return 2 * fee
		}
		return 2*fee + depositOptInMBR
	}
	for _, slots := range []uint64{1, 2, 10} {
		for _, q := range []uint64{0, quota} {
			for _, bal := range []uint64{0, mbr - 1, mbr, 3 * mbr, 3*mbr + 10_000, 3*mbr + quota, 10 * mbr, 10*mbr + quota, 12 * mbr} {
				optedIn := bal > 0
				o := overhead(optedIn)
				for _, sp := range []uint64{
					0, 5_000, o, o + quota - 1, o + quota, o + mbr - 1, o + mbr, o + mbr + quota - 1, o + mbr + quota,
					o + 2*mbr, o + 7*mbr + quota - 1, o + 7*mbr + quota, 100_000_000,
				} {
					ins = append(ins, in{slots, mbr, q, bal, 0, optedIn, sp, fee})
				}
			}
		}
	}
	ins = append(ins,
		// The opt-in MBR counts only on a first deposit.
		in{10, mbr, 0, 0, 0, true, 2*fee + mbr, fee},
		in{10, mbr, 0, 0, 0, false, 2*fee + mbr, fee},
		// Live tickets don't change the sizing: it's on gross balance.
		in{10, mbr, quota, 3 * mbr, 3, true, 50_000, fee},
		in{10, mbr, 0, 10 * mbr, 7, true, 100_000_000, fee},
		// A remainder short of the quota term, partly covering it.
		in{10, mbr, quota, 3*mbr + 10_000, 0, true, 2*fee + quota - 10_000, fee},
		in{10, mbr, quota, 3*mbr + 10_000, 0, true, 2*fee + quota - 10_001, fee},
		// A quota term at least a slot, so the pool can hold more slots than
		// the working set and still be short.
		in{2, mbr, 2 * mbr, 3 * mbr, 0, true, 100_000_000, fee},
		in{2, mbr, 2 * mbr, 3 * mbr, 0, true, 2*fee + mbr - 1, fee},
		// A target past uint64 saturates rather than wrapping. The first slot
		// count wraps its product to under one slot, so an unsaturated target
		// would read as already covered; the others stay huge either way.
		in{math.MaxUint64/mbr + 1, mbr, 0, 3 * mbr, 0, true, 100_000_000, fee},
		in{math.MaxUint64 / 2, mbr, quota, 3 * mbr, 0, true, 100_000_000, fee},
		in{math.MaxUint64, mbr, 0, 0, 0, false, 1_000_000, fee},
		// A pool backing a slot that owes only the quota term, which the
		// wallet can't cover: the need is the term, not a slot.
		in{3, mbr, quota, 3 * mbr, 0, true, 5_000, fee},
		in{10, mbr, quota, 3*mbr + 10_000, 0, true, 5_000, fee},
		// A larger minimum fee.
		in{10, mbr, 0, mbr, 0, true, 2*10_000 + mbr, 10_000},
		in{10, mbr, 0, mbr, 0, true, 2*10_000 + mbr - 1, 10_000},
	)

	cases := make([]depositPlanCase, len(ins))
	for i, c := range ins {
		p := planDeposit(c.slots, c.ticketMbr, c.quotaDue, escrow.PayerDeposit{AlgoBalance: c.balance, OpenTickets: c.open}, c.optedIn, c.spendable, c.minFee)
		cases[i] = depositPlanCase{
			Slots: u(c.slots), TicketMbr: u(c.ticketMbr), QuotaDue: u(c.quotaDue),
			AlgoBalance: u(c.balance), OpenTickets: u(c.open), OptedIn: c.optedIn,
			Spendable: u(c.spendable), MinFee: u(c.minFee),
			Amount: u(p.Amount), BelowTarget: p.BelowTarget, Unaffordable: p.Unaffordable, Need: u(p.Need),
		}
	}
	f := struct {
		Comment string            `json:"comment"`
		Cases   []depositPlanCase `json:"cases"`
	}{
		Comment: "Generated by proto/go/zs TestDepositPlanVectors. One prepaid-MBR-pool funding pass (planDeposit): amount to deposit, whether the pool is still below the working set, whether it backs no slot and the wallet can't fund one, and what the next useful deposit needs. Quantities are decimal strings.",
		Cases:   cases,
	}
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	out = append(out, '\n')

	if *updateVectors {
		if err := os.WriteFile(depositPlanVectorsPath, out, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(depositPlanVectorsPath)
	if err != nil {
		t.Fatalf("read vectors (regenerate with -update): %v", err)
	}
	if !bytes.Equal(want, out) {
		t.Fatal("deposit_plan_vectors.json is stale; regenerate with -update")
	}
}
