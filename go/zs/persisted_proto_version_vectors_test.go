package zs

// Generates / verifies proto/testdata/persisted_proto_version_vectors.json: the
// protocol version a restored catalog entry carries (minorFloor). The TS SDK
// mirrors it as restoredProtoVersion in sdk/src/catalog/version.ts.
//
//	cd proto/go && go test ./zs -run TestPersistedProtoVersionVectors -update

import (
	"bytes"
	"encoding/json"
	"os"
	"testing"
)

const persistedProtoVersionVectorsPath = "../../testdata/persisted_proto_version_vectors.json"

type persistedProtoVersionCase struct {
	Persisted string `json:"persisted"`
	Want      string `json:"want"`
}

func TestPersistedProtoVersionVectors(t *testing.T) {
	inputs := []string{
		"9.10", "9.2", "9.1", "9.0", "10.7", "1.0",
		"", "garbage", ".5", "9.", "9.2.1", "v9.3", "9..1",
	}
	cases := make([]persistedProtoVersionCase, len(inputs))
	for i, in := range inputs {
		cases[i] = persistedProtoVersionCase{Persisted: in, Want: minorFloor(in)}
	}
	f := struct {
		Comment string                      `json:"comment"`
		Cases   []persistedProtoVersionCase `json:"cases"`
	}{
		Comment: "Generated by proto/go/zs TestPersistedProtoVersionVectors. want is minorFloor(persisted): the version a catalog entry read back from storage carries.",
		Cases:   cases,
	}
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	out = append(out, '\n')

	if *updateVectors {
		if err := os.WriteFile(persistedProtoVersionVectorsPath, out, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(persistedProtoVersionVectorsPath)
	if err != nil {
		t.Fatalf("read vectors (regenerate with -update): %v", err)
	}
	if !bytes.Equal(want, out) {
		t.Fatalf("restored versions differ from %s; if the change is intended, regenerate with -update and review the diff", persistedProtoVersionVectorsPath)
	}
}
