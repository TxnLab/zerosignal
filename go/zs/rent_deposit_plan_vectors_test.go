package zs

// Generates / verifies proto/testdata/rent_deposit_plan_vectors.json: how one
// top-up of the Solana rent pool is sized (planRentDeposit). The TS SDK
// mirrors it as planRentDeposit in sdk/src/solana/rent.ts.
//
//	cd proto/go && go test ./zs -run TestRentDepositPlanVectors -update

import (
	"bytes"
	"encoding/json"
	"math"
	"os"
	"testing"
)

const rentDepositPlanVectorsPath = "../../testdata/rent_deposit_plan_vectors.json"

// Lamports and slot counts are decimal strings, as in deposit_plan_vectors.
type rentDepositPlanCase struct {
	Slots       string `json:"slots"`
	TicketRent  string `json:"ticketRent"`
	PoolRent    string `json:"poolRent"`
	PoolExists  bool   `json:"poolExists"`
	Lamports    string `json:"lamports"`
	OpenTickets string `json:"openTickets"`
	Spendable   string `json:"spendable"`

	Amount       string `json:"amount"`
	BelowTarget  bool   `json:"belowTarget"`
	Unaffordable bool   `json:"unaffordable"`
	Need         string `json:"need"`
}

func TestRentDepositPlanVectors(t *testing.T) {
	// The rents at today's rate: (128 + data) × 6,960 lamports.
	const rent, poolRent, fee = (128 + 275) * 6_960, (128 + 82) * 6_960, solanaSignatureFee
	type in struct {
		slots, ticketRent, poolRent uint64
		pool                        rentPoolReading
		spendable                   uint64
	}
	var ins []in
	pool := func(lamports, open uint64) rentPoolReading {
		return rentPoolReading{exists: true, lamports: lamports, openTickets: open}
	}

	// The grid: no pool, and pools around whole slots, against wallets from
	// empty to rich and at each affordability edge, three working sets.
	for _, slots := range []uint64{1, 2, 10} {
		for _, p := range []rentPoolReading{
			{}, pool(poolRent, 0), pool(poolRent+rent-1, 0), pool(poolRent+rent, 0), pool(poolRent+3*rent, 0),
			pool(poolRent+3*rent+10_000, 0), pool(poolRent+10*rent, 0), pool(poolRent+12*rent, 0),
		} {
			o := fee
			if !p.exists {
				o += poolRent
			}
			for _, sp := range []uint64{0, fee, o, o + rent - 1, o + rent, o + 2*rent, o + 7*rent - 1, o + 7*rent, o + 10*rent, 10_000_000_000} {
				ins = append(ins, in{slots, rent, poolRent, p, sp})
			}
		}
	}
	ins = append(ins,
		// The pool's own rent counts only on a first deposit.
		in{10, rent, poolRent, rentPoolReading{}, fee + poolRent + rent},
		in{10, rent, poolRent, rentPoolReading{}, fee + poolRent + rent - 1},
		in{10, rent, poolRent, pool(poolRent, 0), fee + rent},
		// Lamports at the address before the first deposit don't make a pool.
		in{10, rent, poolRent, rentPoolReading{lamports: 5 * rent}, fee + poolRent + rent},
		// Live tickets' rent sits in the tickets and counts toward the pool.
		in{10, rent, poolRent, pool(poolRent, 3), 10_000_000_000},
		in{10, rent, poolRent, pool(poolRent+rent, 9), 10_000_000_000},
		in{10, rent, poolRent, pool(poolRent, 10), 0},
		in{3, rent, poolRent, pool(poolRent+2*rent, 3), 0},
		// A pool below its own rent backs nothing, rather than wrapping.
		in{10, rent, poolRent, pool(poolRent-1, 0), fee + rent},
		in{10, rent, poolRent, pool(0, 2), 10_000_000_000},
		// A part slot in the pool counts toward the next: 3 slots and 10,000
		// over, with what the slot lacks spendable past the fee, buys a 4th.
		in{10, rent, poolRent, pool(poolRent+3*rent+10_000, 0), fee + rent - 10_000},
		in{10, rent, poolRent, pool(poolRent+3*rent+10_000, 0), fee + rent - 10_001},
		// Live tickets and lamports past uint64 together saturate.
		in{10, rent, poolRent, pool(poolRent, math.MaxUint64/rent+1), 0},
		in{math.MaxUint64, rent, poolRent, pool(math.MaxUint64, 1), 10_000_000_000},
		// A target past uint64 saturates rather than wrapping.
		in{math.MaxUint64/rent + 1, rent, poolRent, pool(poolRent+3*rent, 0), 10_000_000_000},
		in{math.MaxUint64, rent, poolRent, rentPoolReading{}, 1_000_000_000},
		// Another rate.
		in{10, 2 * rent, 2 * poolRent, pool(2*poolRent, 0), fee + 2*rent},
		in{10, 2 * rent, 2 * poolRent, pool(2*poolRent, 0), fee + 2*rent - 1},
	)

	cases := make([]rentDepositPlanCase, len(ins))
	for i, c := range ins {
		p := planRentDeposit(c.slots, c.ticketRent, c.poolRent, c.pool, c.spendable)
		cases[i] = rentDepositPlanCase{
			Slots: u(c.slots), TicketRent: u(c.ticketRent), PoolRent: u(c.poolRent),
			PoolExists: c.pool.exists, Lamports: u(c.pool.lamports), OpenTickets: u(c.pool.openTickets),
			Spendable: u(c.spendable),
			Amount:    u(p.Amount), BelowTarget: p.BelowTarget, Unaffordable: p.Unaffordable, Need: u(p.Need),
		}
	}
	f := struct {
		Comment      string                `json:"comment"`
		SignatureFee string                `json:"signatureFee"`
		Cases        []rentDepositPlanCase `json:"cases"`
	}{
		Comment:      "Generated by proto/go/zs TestRentDepositPlanVectors. One top-up of the Solana rent pool (planRentDeposit): lamports to deposit, whether the pool is still below the working set, whether it backs no slot and the wallet can't fund one, and what the next useful deposit needs. lamports is the pool account's balance, its own rent included; spendable is the payer's above its reserve. Quantities are decimal strings.",
		SignatureFee: u(solanaSignatureFee),
		Cases:        cases,
	}
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	out = append(out, '\n')

	if *updateVectors {
		if err := os.WriteFile(rentDepositPlanVectorsPath, out, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(rentDepositPlanVectorsPath)
	if err != nil {
		t.Fatalf("read vectors (regenerate with -update): %v", err)
	}
	if !bytes.Equal(want, out) {
		t.Fatal("rent_deposit_plan_vectors.json is stale; regenerate with -update")
	}
}
